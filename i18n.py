def set_language(code: str) -> None:
    global _lang
    _lang = code if code in STRINGS else "en"


def current() -> str:
    return _lang


def detect_language() -> str:
    """Windows display language: Catalan or Spanish if that's what the user has, else English."""
    try:
        import ctypes
        primary = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
        return {0x03: "ca", 0x0A: "es"}.get(primary, "en")
    except Exception:
        return "en"


def t(key: str, **kwargs) -> str:
    text = STRINGS.get(_lang, {}).get(key) or STRINGS["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text


def weekday_short(index: int) -> str:
    """0 = Monday."""
    return t("weekdays").split()[index]
